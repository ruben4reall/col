struct ClipboardSearchTests {
    let now = Date(timeIntervalSince1970: 0)

    @Test func findsEveryWordWhateverTheCaseAndAccents() {
        var history = ClipboardHistory()
        history.add("Rendez-vous à l'Hôtel de Ville", at: now, from: "Mail")
        history.add("git push origin main", at: now, from: "Terminal")
        history.add("Hotel booking reference 42", at: now, from: "Safari")
        #expect(history.matching("hotel").map(\.text) == ["Hotel booking reference 42", "Rendez-vous à l'Hôtel de Ville"])
        #expect(history.matching("HOTEL ville").map(\.text) == ["Rendez-vous à l'Hôtel de Ville"])
        // The app it was copied from counts too.
        #expect(history.matching("terminal").map(\.text) == ["git push origin main"])
        #expect(history.matching("  ").count == 3)
        #expect(history.matching("nothing like it").isEmpty)
    }

    @Test func pinsStayFirstInResults() {
        var history = ClipboardHistory()
        history.add("note one", at: now)
        history.togglePin(history.entries[0].id)
        history.add("note two", at: now)
        #expect(history.matching("note").map(\.text) == ["note one", "note two"])
    }

    @Test func passwordManagersCopiesAreSkipped() {
        #expect(PasteboardPrivacy.isPrivate(["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        #expect(PasteboardPrivacy.isPrivate(["org.nspasteboard.TransientType"]))
        #expect(PasteboardPrivacy.isPrivate(["org.nspasteboard.AutoGeneratedType", "public.utf8-plain-text"]))
        #expect(PasteboardPrivacy.isPrivate(["com.agilebits.onepassword"]))
        #expect(!PasteboardPrivacy.isPrivate(["public.utf8-plain-text", "public.html"]))
        #expect(!PasteboardPrivacy.isPrivate([String]()))
    }
}

struct ShelfToolsTests {
    @Test func convertsImagesToTheOtherFormats() {
        #expect(ShelfTools.conversions(for: URL(fileURLWithPath: "/a/Photo.HEIC")) == [.png, .jpeg])
        #expect(ShelfTools.conversions(for: URL(fileURLWithPath: "/a/Shot.png")) == [.jpeg, .heic])
        #expect(ShelfTools.conversions(for: URL(fileURLWithPath: "/a/Scan.tiff")) == [.png, .jpeg, .heic])
        #expect(ShelfTools.conversions(for: URL(fileURLWithPath: "/a/Report.pdf")).isEmpty)
    }

    @Test func resizesByHalfOrToPoints() {
        #expect(ShelfTools.size(.half, width: 3024, height: 1964, dpi: 144)! == (1512, 982))
        #expect(ShelfTools.size(.pointSize, width: 3024, height: 1964, dpi: 144)! == (1512, 982))
        #expect(ShelfTools.size(.pointSize, width: 900, height: 600, dpi: 216)! == (300, 200))
        // A capture already at 1x, or with no resolution, stays as it is.
        #expect(ShelfTools.size(.pointSize, width: 800, height: 600, dpi: 72) == nil)
        #expect(ShelfTools.size(.pointSize, width: 800, height: 600, dpi: nil) == nil)
        #expect(ShelfTools.size(.half, width: 1, height: 1, dpi: nil) == nil)
    }

    @Test func resultsNeverReplaceAFile() {
        let source = URL(fileURLWithPath: "/Users/me/Desktop/Photo.png")
        let taken: Set<String> = ["/Users/me/Desktop/Photo.jpg", "/Users/me/Desktop/Photo 2.jpg"]
        let jpeg = ShelfTools.destination(for: source, fileExtension: "jpg") { taken.contains($0.path) }
        #expect(jpeg.path == "/Users/me/Desktop/Photo 3.jpg")
        let half = ShelfTools.destination(for: source, suffix: "50%", fileExtension: "png") { _ in false }
        #expect(half.lastPathComponent == "Photo 50%.png")
    }
}

struct GraphicsProcessorTests {
    @Test func readsTheGraphicsProcessorsLoad() {
        #expect(SystemMath.gpuUsage(["Device Utilization %": NSNumber(value: 9), "Renderer Utilization %": NSNumber(value: 7)]) == 0.09)
        #expect(SystemMath.gpuUsage(["GPU Activity(%)": NSNumber(value: 40)]) == 0.4)
        #expect(SystemMath.gpuUsage(["Device Utilization %": NSNumber(value: 140)]) == 1)
        #expect(SystemMath.gpuUsage(["Alloc system memory": NSNumber(value: 2_154_463_232)]) == nil)
    }
}
